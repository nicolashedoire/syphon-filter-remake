'use strict';
const assert=require('node:assert/strict');
global.window=global;
require('../web/math.js');
require('../web/metro-fires.js');
require('../web/metro-fire-effects.js');
assert.ok(SF_METRO_FIRES.length>100,'original mission fire records loaded');
const draws=[];
const renderer={visibleRooms:new Set([19]),draw(mesh,matrix,color,scene){draws.push({mesh,matrix,color,scene});}};
const mesh={},player={x:-14.37,y:-11.19,z:-1.16};
SFMetroFireEffects.draw(renderer,mesh,SF_METRO_FIRES,player,1);
assert.ok(draws.length>0 && draws.length<=32 && draws.length%2===0,'bounded visible fire geometry');
assert.ok(draws.every(d=>d.matrix.every(Number.isFinite)&&d.color.every(Number.isFinite)&&!d.scene));
const first=draws[0].matrix.slice();draws.length=0;
SFMetroFireEffects.draw(renderer,mesh,SF_METRO_FIRES,player,1.2);
assert.notDeepEqual(draws[0].matrix,first,'fire flickers over time');
draws.length=0;renderer.visibleRooms=new Set();
SFMetroFireEffects.draw(renderer,mesh,SF_METRO_FIRES,player,2);
assert.equal(draws.length,0,'invisible rooms are culled');
console.log('Metro fire effects: original placements, room/distance culling and bounded animated drawing passed.');
